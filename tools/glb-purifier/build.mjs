import { NodeIO, Document } from '@gltf-transform/core';
import { KHRMeshQuantization } from '@gltf-transform/extensions';
import { quantize } from '@gltf-transform/functions';
import fs from 'fs';
const f32 = n => { const b = fs.readFileSync(n); return new Float32Array(b.buffer, b.byteOffset, b.byteLength/4); };
const u32 = n => { const b = fs.readFileSync(n); return new Uint32Array(b.buffer, b.byteOffset, b.byteLength/4); };
const doc = new Document(); const buf = doc.createBuffer();
const pos = doc.createAccessor().setType('VEC3').setArray(f32('f_pos.bin')).setBuffer(buf);
const nrm = doc.createAccessor().setType('VEC3').setArray(f32('f_nrm.bin')).setBuffer(buf);
const uv = doc.createAccessor().setType('VEC2').setArray(f32('f_uv.bin')).setBuffer(buf);
const idx = doc.createAccessor().setType('SCALAR').setArray(u32('f_idx.bin')).setBuffer(buf);
const bt = doc.createTexture('base').setImage(fs.readFileSync('f_base.jpg')).setMimeType('image/jpeg');
const mt = doc.createTexture('mr').setImage(fs.readFileSync('f_mr.jpg')).setMimeType('image/jpeg');
const mat = doc.createMaterial('purifier').setBaseColorTexture(bt).setMetallicRoughnessTexture(mt).setMetallicFactor(1).setRoughnessFactor(1).setDoubleSided(true);
const prim = doc.createPrimitive().setAttribute('POSITION', pos).setAttribute('NORMAL', nrm).setAttribute('TEXCOORD_0', uv).setIndices(idx).setMaterial(mat);
const mesh = doc.createMesh('m').addPrimitive(prim);
const node = doc.createNode('n').setMesh(mesh);
doc.createScene('s').addChild(node);
const io = new NodeIO().registerExtensions([KHRMeshQuantization]);
if (process.env.QUANT) await doc.transform(quantize({ quantizePosition: 14, quantizeNormal: 8, quantizeTexcoord: 16, patternTargets: undefined }));
await io.write(process.argv[2], doc);
